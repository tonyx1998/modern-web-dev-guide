function stripBom(text) {
  return text.charCodeAt(0) === 0xfeff ? text.slice(1) : text;
}

function parseFrontmatter(filePath) {
  const raw = stripBom(fs.readFileSync(filePath, 'utf8'));
  const m = raw.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!m) return {};
  const fm = {};
  for (const line of m[1].split('\n')) {
    const kv = line.match(/^(\w+):\s*(.+)$/);
    if (kv) fm[kv[1]] = kv[2].trim().replace(/^['"]|['"]$/g, '');
  }
  return fm;
}

function extractQuizId(filePath) {
  const raw = stripBom(fs.readFileSync(filePath, 'utf8'));
  const m = raw.match(/<Quiz\s+id="([^"]+)"/);
  return m?.[1] ?? null;
}

function readCategoryPosition(dir) {
  const catFile = path.join(dir, '_category_.json');
  if (!fs.existsSync(catFile)) return null;
  try {
    return JSON.parse(fs.readFileSync(catFile, 'utf8')).position ?? 999;
  } catch {
    return 999;
  }
}

/** Walk autogenerated chapter dir in Docusaurus-like order. */
function autogenOrder(chapterSlug, dirName) {
  const base = path.join(DOCS, dirName);
  const ordered = [];

  function walk(absDir) {
    const items = [];
    for (const ent of fs.readdirSync(absDir, {withFileTypes: true})) {
      if (ent.name.startsWith('_')) continue;
      const fp = path.join(absDir, ent.name);
      if (ent.isDirectory()) {
        items.push({
          kind: 'dir',
          sortKey: readCategoryPosition(fp) ?? 999,
          path: fp,
        });
      } else if (ent.name.endsWith('.md')) {
        const fm = parseFrontmatter(fp);
        if (!fm.id) continue;
        items.push({
          kind: 'doc',
          sortKey: Number(fm.sidebar_position ?? 999),
          docPath: `${chapterSlug}/${fm.id}`,
        });
      }
    }
    items.sort((a, b) => a.sortKey - b.sortKey || a.kind.localeCompare(b.kind));

    for (const item of items) {
      if (item.kind === 'doc') {
        ordered.push(item.docPath);
      } else {
        walk(item.path);
      }
    }
  }

  walk(base);
  return ordered;
}

function docPathToFile(chapterSlug, docId) {
  const dirMap = {
    foundations: '01-foundations',
    roadmap: '02-roadmap',
    lifecycle: '03-lifecycle',
    stack: '04-stack',
    solo: '05-solo',
    startup: '06-startup',
    enterprise: '07-enterprise',
    comparison: '08-comparison',
    decisions: '09-decisions',
    ai: '10-ai',
    career: '11-career',
    cloud: '12-cloud',
    operations: '13-operations',
    'distributed-systems': '14-distributed-systems',
    ecosystems: '15-ecosystems',
  };
  const baseDir = path.join(DOCS, dirMap[chapterSlug]);
  function findIn(dir) {
    for (const ent of fs.readdirSync(dir, {withFileTypes: true})) {
      const p = path.join(dir, ent.name);
      if (ent.isDirectory()) {
        const hit = findIn(p);
        if (hit) return hit;
      } else if (ent.name.endsWith('.md')) {
        const fm = parseFrontmatter(p);
        if (fm.id === docId) return p;
      }
    }
    return null;
  }
  return findIn(baseDir);
}

function buildChapterData(chapterSlug, order) {
  const checkpoints = {};
  const filteredOrder = [];
  for (const docPath of order) {
    const [, docId] = docPath.split('/');
    const file = docPathToFile(chapterSlug, docId);
    if (!file) {
      console.warn(`warn: no file for ${docPath}`);
      continue;
    }
    const quizId = extractQuizId(file);
    if (quizId) {
      checkpoints[docPath] = quizId;
      filteredOrder.push(docPath);
    }
  }
  return {checkpoints, order: filteredOrder};
}

const CHAPTER_PAGE_ORDER = {};
const PAGE_CHECKPOINTS = {};

for (const [chapter, order] of Object.entries(MANUAL_ORDER)) {
  const data = buildChapterData(chapter, order);
  CHAPTER_PAGE_ORDER[chapter] = data.order;
  Object.assign(PAGE_CHECKPOINTS, data.checkpoints);
}

for (const [chapter, dirName] of Object.entries(AUTOGEN_DIRS)) {
  const order = autogenOrder(chapter, dirName);
  const data = buildChapterData(chapter, order);
  CHAPTER_PAGE_ORDER[chapter] = data.order;
  Object.assign(PAGE_CHECKPOINTS, data.checkpoints);
}

